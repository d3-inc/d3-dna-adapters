// Builds cloudflare-snippet/snippet.js from cloudflare-snippet/src/. The pasted
// file is an artifact, never edited: the logic it shares with the npm adapters
// comes from packages/protocol, so a protocol fix reaches a snippet install
// instead of waiting for someone to notice the copy.
//
//   pnpm generate:snippet          rebuild and write
//   pnpm generate:snippet --check  rebuild and fail on any difference (CI)
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { format, resolveConfig } from 'prettier';

const ROOT = new URL('../', import.meta.url);

const ENTRY = new URL('cloudflare-snippet/src/snippet.ts', ROOT);

const CONFIG_BLOCK = new URL('cloudflare-snippet/src/config.js', ROOT);

const OUTPUT = new URL('cloudflare-snippet/snippet.js', ROOT);

/**
 * Cloudflare rejects a Snippet over this, so a build that passes CI and fails
 * the paste is the one failure this budget exists to catch
 * (https://developers.cloudflare.com/rules/snippets/#limits).
 */
const MAX_PACKAGE_BYTES = 32 * 1024;

const HEADER = `// Generated by scripts/generate-snippet.ts — do not edit.
// Source: cloudflare-snippet/src/snippet.ts, bundled with the shared logic from
// packages/protocol. Rebuild with \`pnpm generate:snippet\`.
//
// Paste this whole file into Rules → Snippets and edit CONFIG below; nothing
// under it needs changing. See cloudflare-snippet/README.md.
`;

async function render(): Promise<string> {
  const bundle = await build({
    entryPoints: [fileURLToPath(ENTRY)],
    bundle: true,
    write: false,
    format: 'esm',
    // The Workers runtime, and no platform shims: a Snippet has no Node built-ins.
    platform: 'neutral',
    target: 'es2022',
    // Readable on purpose. Customers review what they paste into their own CDN,
    // and a minified blob is not reviewable; the size budget below is what pays for it.
    minify: false,
    charset: 'utf8',
    legalComments: 'none',
    metafile: true,
  });

  // A Snippet installs nothing, so anything reached through node_modules is a
  // dependency the paste would be missing. The protocol's barrel is the way in:
  // it re-exports the logger, and logtape alone is 48 KB of a 32 KB budget.
  const dependency = Object.keys(bundle.metafile.inputs).find((input) => input.includes('node_modules'));
  if (dependency !== undefined) {
    throw new Error(
      `the snippet bundle reached a package: ${dependency}. Import the module, not the barrel.`
    );
  }

  const [out] = bundle.outputFiles;
  // The config block is prepended rather than bundled, so the customer edits the
  // top of the file; the bundle reads `CONFIG` as a free variable. A module that
  // declared its own would shadow the block and the paste would silently run on
  // esbuild's binding instead of the customer's settings.
  if (/\b(?:var|let|const|function|class)\s+CONFIG\b/.test(out.text)) {
    throw new Error('the snippet bundle declares its own CONFIG, which shadows the pasted block');
  }

  if (!/\bCONFIG\b/.test(out.text)) {
    throw new Error('the snippet bundle never reads CONFIG, so the pasted settings do nothing');
  }

  const config = await readFile(CONFIG_BLOCK, 'utf8');
  const source = `${HEADER}\n${config}\n${out.text}`;
  const options = await resolveConfig(fileURLToPath(OUTPUT));
  return format(source, { ...options, parser: 'babel' });
}

function sizeReport(source: string): string {
  const bytes = Buffer.byteLength(source, 'utf8');
  const percent = ((bytes / MAX_PACKAGE_BYTES) * 100).toFixed(1);
  return `${bytes} bytes, ${percent}% of Cloudflare's ${MAX_PACKAGE_BYTES}-byte Snippet budget`;
}

const generated = await render();
const report = sizeReport(generated);

if (Buffer.byteLength(generated, 'utf8') > MAX_PACKAGE_BYTES) {
  console.error(`snippet.js is over budget: ${report}`);
  process.exit(1);
}

if (process.argv.includes('--check')) {
  const committed = await readFile(OUTPUT, 'utf8').catch(() => '');
  if (committed !== generated) {
    console.error(
      'cloudflare-snippet/snippet.js is stale: it does not match a fresh build of\n' +
        'cloudflare-snippet/src/. Run `pnpm generate:snippet` and commit the result.'
    );
    process.exit(1);
  }

  console.log(`snippet.js is current (${report})`);
} else {
  await writeFile(OUTPUT, generated);
  console.log(`wrote cloudflare-snippet/snippet.js (${report})`);
}
